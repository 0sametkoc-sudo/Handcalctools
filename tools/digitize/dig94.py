def snap_curve(img,P,seeds,gate=5.0):
    X,Y=P["X"],P["Y"]
    sx=np.array([0.0]+[s[0] for s in seeds]); sy=np.array([0.0]+[s[1] for s in seeds])
    vg=set(expand([int(round(float(X.pix(v)))) for v in np.arange(0,1.0001,0.1)],2))
    hg=set(expand([int(round(float(Y.pix(v)))) for v in np.arange(0,1.0001,0.2)],2))
    xs,ys=[],[]
    for x in range(P["xr"][0],P["xr"][1]+1):
        if x in vg: continue
        xv=float(X.val(x))
        if xv<0.01 or xv>0.99: continue
        pred=float(Y.pix(np.interp(xv,sx,sy)))
        rs=[r[0] for r in column_runs(img,x,P["yr"][0],P["yr"][1],150) if r[1]<=5 and int(round(r[0])) not in hg]
        if rs:
            c=min(rs,key=lambda r:abs(r-pred))
            if abs(c-pred)<=gate:
                xs.append(xv); ys.append(float(Y.val(c)))
    return np.array(xs),np.array(ys)


def run():
    img=load(SRC)
    out={}
    for fr,P in PANELS.items():
        curves={}
        for prm in PARAM:
            x,y=snap_curve(img,P,P["seeds"][prm])
            x,y=despike(x,y,win=6,tol=0.03)
            sx=np.array([0.0]+[s[0] for s in P["seeds"][prm]]); sy=np.array([0.0]+[s[1] for s in P["seeds"][prm]])
            g=np.interp(GRID,np.r_[0.0,x,1.0],np.r_[0.0,y,1.0]) if len(x) else np.interp(GRID,sx,sy)
            # where no pixel was snapped over a stretch > 0.06, keep the visually read guide value
            for i,v in enumerate(GRID):
                if len(x)==0 or np.min(np.abs(x-v))>0.02:
                    g[i]=np.interp(v,sx,sy)
            curves[prm]=np.clip(g,0,1)
        # curves do not cross: Kn decreases with Ftu/(E eu)
        for i in range(len(PARAM)-2,-1,-1):
            curves[PARAM[i]]=np.maximum(curves[PARAM[i]],curves[PARAM[i+1]])
        for prm in PARAM:
            curves[prm][0]=0.0; curves[prm][-1]=1.0
        out[fr]=curves
    return out


