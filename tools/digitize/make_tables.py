"""Generate handcalc/afsam_charts.py (digitized AFSAM Section 9 charts) and the overlay check images.

python tools/digitize/make_tables.py
"""
import os, sys
import numpy as np
HERE=os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0,HERE)
os.chdir(HERE)
from digitize_common import overlay, despike
import dig_simple, dig93, dig94

ROOT=os.path.dirname(os.path.dirname(HERE))
FIG=os.path.join(ROOT,'docs','figures')


def r(a, n=3):
    return [None if (v is None or (isinstance(v, float) and np.isnan(v))) else round(float(v), n) for v in a]


def main():
    out = ['"""Digitized AFSAM (1986) Section 9 charts - GENERATED by tools/digitize/make_tables.py, do not edit.',
           '',
           'Source: Stress Analysis Manual, Air Force Flight Dynamics Laboratory, Oct. 1986, Section 9',
           '(public domain). Curves were extracted from the figure scans by pixel tracking guided by visually read',
           'points, and checked by drawing them back over the scans (docs/figures/afsam_fig*_digitized.png).',
           'Reading accuracy is about +/-0.01 to 0.02 in the coefficient.',
           '"""', '']
    # Fig 9-2
    x, y, X, Y = dig_simple.fig9_2()
    x, y = despike(x, y, tol=0.02)
    g92 = np.round(np.arange(0.5, 2.4001, 0.05), 3)
    k92 = np.interp(g92, x, y)
    overlay(dig_simple.SRC + 'afsam_fig9_2_page.png', os.path.join(FIG, 'afsam_fig9_2_digitized.png'),
            [('K', g92, k92)], X, Y, crop=(470, 350, 900, 740), dot=2.2)
    out += ['# Figure 9-2: allowable axial load coefficient K versus e/D (D/t <= 5)',
            f'FIG9_2_ED = {r(g92)}', f'FIG9_2_K = {r(k92)}', '']
    # Fig 9-8
    (xu, yu), (xl, yl), X, Y = dig_simple.fig9_8()
    m = xu <= 1.47
    xu, yu = despike(xu[m], yu[m]); xl, yl = despike(xl[m], yl[m])
    g98 = np.round(np.arange(0.0, 1.4501, 0.05), 3)
    ku, ky = np.interp(g98, np.r_[0, xu], np.r_[0, yu]), np.interp(g98, np.r_[0, xl], np.r_[0, yl])
    ky = np.minimum(ky, ku)
    overlay(dig_simple.SRC + 'afsam_fig9_8_page.png', os.path.join(FIG, 'afsam_fig9_8_digitized.png'),
            [('Ktru', g98, ku), ('Ktry', g98, ky)], X, Y, crop=(440, 520, 920, 780), dot=2.2)
    out += ['# Figure 9-8: transverse ultimate and yield load coefficients versus hav/D',
            f'FIG9_8_HAVD = {r(g98)}', f'FIG9_8_KTRU = {r(ku)}', f'FIG9_8_KTRY = {r(ky)}', '']
    # Fig 9-3
    c93 = dig93.run()
    cut = dig93.cutoffs()
    g = dig93.GRID
    # value at a/D = 0.5 from the common envelope through the origin of the curves (a/D ~ 0.48)
    overlay(dig93.SRC, os.path.join(FIG, 'afsam_fig9_3_digitized.png'),
            [(str(d), g, c93[d]) for d in dig93.DT] + [('A', g, cut['A']), ('B', g, cut['B'])],
            dig93.X, dig93.Y, crop=(400, 0, 990, 480), dot=1.8)
    out += ['# Figure 9-3: bearing efficiency factor K versus a/D for D/t curves (Al alloys, steel Ftu < 160 ksi)',
            f'FIG9_3_AD = {r(g)}', f'FIG9_3_DT = {dig93.DT}', 'FIG9_3_K = {']
    out += [f'    {d}: {r(c93[d])},' for d in dig93.DT] + ['}',
            '# cut-off curves (None = not applicable at that a/D); held constant right of a/D ~ 2.1',
            f'FIG9_3_CUT_A = {r(cut["A"])}', f'FIG9_3_CUT_B = {r(cut["B"])}', '']
    # Fig 9-4
    c94 = dig94.run()
    for fr, P in dig94.PANELS.items():
        tag = {1.0: 'b', 0.8: 'c', 0.6: 'd'}[fr]
        overlay(dig94.SRC, os.path.join(FIG, f'afsam_fig9_4{tag}_digitized.png'),
                [(str(p), dig94.GRID, c94[fr][p]) for p in dig94.PARAM], P['X'], P['Y'],
                crop=(P['xr'][0] - 10, P['yr'][0] - 12, P['xr'][1] + 10, P['yr'][1] + 10), dot=1.8)
    out += ['# Figure 9-4: net-tension stress coefficient Kn versus D/w;',
            '# panels Fty/Ftu = 1.0 / 0.8 / 0.6, curves Ftu/(E eu) = 0 ... 1.0',
            f'FIG9_4_DW = {r(dig94.GRID)}', f'FIG9_4_FTY_FTU = [0.6, 0.8, 1.0]', f'FIG9_4_Q = {dig94.PARAM}',
            'FIG9_4_KN = {']
    for fr in (0.6, 0.8, 1.0):
        out.append(f'    {fr}: {{')
        out += [f'        {p}: {r(c94[fr][p])},' for p in dig94.PARAM]
        out.append('    },')
    out.append('}')
    path = os.path.join(ROOT, 'handcalc', 'afsam_charts.py')
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(path)


if __name__ == '__main__':
    main()
