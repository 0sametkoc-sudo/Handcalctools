def lug_formula(tmpl, s, dp_name):
    edc, dwx = f"edc_{s}", f"MIN(MAX(Dw_{s},0),1)"
    n93, n94 = len(ch.FIG9_3_AD), len(ch.FIG9_4_DW)
    rep = {
        "{K92}": lin(f"ed_{s}", "chart92", 0.5, 0.05, len(ch.FIG9_2_K)),
        "{KA93}": lin(edc, "chart93", 0.5, 0.05, n93, col=f"j93_{s}"),
        "{KB93}": lin(edc, "chart93", 0.5, 0.05, n93, col=f"j93_{s}+1"),
        "{CA}": lin(edc, "chart93A", 0.5, 0.05, n93),
        "{CB}": lin(edc, "chart93B", 0.5, 0.05, n93),
        "{K11}": lin(dwx, "chart94", 0, 0.025, n94, col=f"(jp_{s}-1)*7+jq_{s}"),
        "{K12}": lin(dwx, "chart94", 0, 0.025, n94, col=f"(jp_{s}-1)*7+jq_{s}+1"),
        "{K21}": lin(dwx, "chart94", 0, 0.025, n94, col=f"jp_{s}*7+jq_{s}"),
        "{K22}": lin(dwx, "chart94", 0, 0.025, n94, col=f"jp_{s}*7+jq_{s}+1"),
        "{DP}": dp_name,
    }
    f = tmpl
    for k, v in rep.items():
        f = f.replace(k, v)
    return f.replace("{s}", s)


def write_lug_inputs(wb, ws, F, r, cols, defaults, sheet):
    """cols: {suffix: column index}. defaults: {suffix: {key: value}}."""
    for key, label, sym, unit, desc, kind in LUG_IN:
        ws.write(r, 1, label)
        ws.write(r, 2, sym)
        for s, c in cols.items():
            v = defaults[s].get(key)
            if isinstance(kind, tuple):
                ws.write(r, c, v if v is not None else kind[1][0], F["intxt"])
                ws.data_validation(r, c, r, c, {"validate": "list", "source": kind[1]})
            elif v is None:
                ws.write_blank(r, c, None, F["in"])
            else:
                ws.write_number(r, c, v, F["in"])
            wb.define_name(f"{key}_{s}", f"='{sheet}'!${xl_col(c)}${r + 1}")
        ws.write(r, max(cols.values()) + 1, unit)
        ws.write(r, max(cols.values()) + 2, desc, F["txt"])
        if len(desc) > 95:
            ws.set_row(r, 27 if len(desc) < 190 else 40)
        r += 1
    return r


def write_lug_calc(wb, ws, F, r, cols, sheet, dp_names):
    for spec in LUG_CALC:
        if spec[0] == "sec":
            ws.merge_range(r, 1, r, max(cols.values()) + 2, spec[1], F["sec"])
            r += 1
            continue
        key, desc, sym, tmpl, unit, eq = spec
        ws.write(r, 1, desc)
        ws.write(r, 2, sym)
        for s, c in cols.items():
            fmt = F["calc0"] if unit == "N" else (F["calcg"] if key in ("fig",) else F["calc"])
            ws.write_formula(r, c, lug_formula(tmpl, s, dp_names[s]), fmt)
            wb.define_name(f"{key}_{s}", f"='{sheet}'!${xl_col(c)}${r + 1}")
        ws.write(r, max(cols.values()) + 1, unit)
        ws.write(r, max(cols.values()) + 2, eq, F["small"])
        r += 1
    return r


def xl_col(c):
    s = ""
    c += 1
    while c:
        c, rem = divmod(c - 1, 26)
        s = chr(65 + rem) + s
    return s


