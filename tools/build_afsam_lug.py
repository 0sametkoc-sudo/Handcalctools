def simple_inputs(wb, ws, F, r, items, sheet, col=3):
    for key, label, sym, v, unit, desc in items:
        ws.write(r, 1, label)
        ws.write(r, 2, sym)
        if isinstance(v, tuple):
            ws.write(r, col, v[0], F["intxt"])
            ws.data_validation(r, col, r, col, {"validate": "list", "source": list(v[1])})
        elif v is None:
            ws.write_blank(r, col, None, F["in"])
        else:
            ws.write_number(r, col, v, F["in"])
        ws.write(r, col + 1, unit)
        ws.write(r, col + 2, desc, F["txt"])
        wb.define_name(key, f"='{sheet}'!${xl_col(col)}${r + 1}")
        r += 1
    return r


