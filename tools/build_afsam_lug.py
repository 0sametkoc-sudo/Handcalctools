def lin(xexpr, tbl, x0, dx, n, col=None):
    """Excel expression: linear interpolation of an equally spaced table (clamped)."""
    xc = f"MIN(MAX({xexpr},{x0}),{x0 + dx * (n - 1)})"
    i = f"MIN(INT(({xc}-{x0})/{dx}+1E-9),{n - 2})"
    if col is None:
        a, b = f"INDEX({tbl},{i}+1)", f"INDEX({tbl},{i}+2)"
    else:
        a, b = f"INDEX({tbl},{i}+1,{col})", f"INDEX({tbl},{i}+2,{col})"
    return f"({a}+({xc}-({x0}+{i}*{dx}))/{dx}*({b}-{a}))"


